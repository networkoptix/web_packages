@swagger_auto_schema(method="POST",  auto_schema=None,
                     operation_description="Sends an mass email to all users belonging to targeted emails."
                                           "This is mainly used for things like announcing cloud maintenance.",
                     request_body=openapi.Schema(
                         type=openapi.TYPE_OBJECT,
                         properties={
                             "customizations": customizations__body,
                             "Preview": preview__body,
                             "Save": save__body,
                             "Send": send__body
                         }
                     ))
@api_view(['POST'])
@permission_classes((IsAuthenticated, ))
def cloud_notification_action(request):
    can_add = request.user.has_perm('notifications.add_cloudnotification')
    can_change = request.user.has_perm(
        'notifications.change_cloudnotification')
    can_send = request.user.has_perm('notifications.send_cloud_notification')

    customizations = [request.CUSTOMIZATION]
    if 'customizations' in request.data:
        customizations = request.data.getlist('customizations')

    for customization in customizations:
        if not UserGroupsToAssetPermissions.check_customization_permission(request.user,
                                                                           customization,
                                                                           'notifications.send_cloud_notification'):
            raise PermissionDenied

    notification_id = str(update_or_create_notification(
        request.data, customizations))

    if (can_add and not notification_id or can_change) and 'Save' in request.data:
        messages.success(request._request, "Changes have been saved")

    elif (can_add and not notification_id or can_change) and 'Preview' in request.data:
        request_target_users = request.data.getlist(
            'test_users', default=[request.user.id])

        target_users = Account.objects.filter(id__in=request_target_users)
        original_message = format_message(
            CloudNotification.objects.get(id=notification_id))

        for user in target_users:
            message = original_message.copy()
            message["userFullName"] = user.get_full_name()
            notifications_api.send(
                user.email, 'cloud_notification', message,
                customization=user.customization or getattr(request, 'CUSTOMIZATION', customization_ctx.get()))
        messages.success(request._request, "Preview has been sent")

    elif can_send and 'Send' in request.data and notification_id:
        force = 'ignore_subscriptions' in request.data

        notification = CloudNotification.objects.get(id=notification_id)
        message = format_message(notification)

        notification.sent_by = request.user
        notification.sent_date = timezone.now()
        notification.save()
        send_to_all_users.apply_async(args=[notification_id, message, customizations, force],
                                      queue=settings.NOTIFICATIONS_CONFIG['cloud_notification']['queue'])
        messages.success(request._request, "Sending cloud notifications")

    else:
        messages.error(request._request,
                       "Insufficient permission or invalid action")

    if not can_change:
        return redirect('/admin/notifications/')
    return redirect(reverse('admin:notifications_cloudnotification_change', args=[notification_id]))


