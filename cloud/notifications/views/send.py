# Replaces </p> and <br> with \n and then remove all html tags
def html_to_text(html):
    new_line = re.compile(r'<(\/p|br)>')
    tags = re.compile(r'<[\w\=\'\"\:\;\_\-\,\!\/\ ]+>')
    return tags.sub('', new_line.sub('\n', html))


def add_brs(html):
    br = re.compile(r'\n')
    return br.sub('<br>', html)


def format_message(notification):
    message = dict()
    message['subject'] = notification.subject
    message['html_body'] = add_brs(notification.body)
    message['text_body'] = html_to_text(notification.body)
    return message


def update_or_create_notification(data, customizations=None):
    if not data['id']:
        notification = CloudNotification(
            subject=data['subject'], body=data['body'])
    else:
        notification = CloudNotification.objects.get(id=data['id'])
        notification.subject = data['subject']
        notification.body = data['body']
        notification.save()
        if customizations:
            notification.customizations.set(
                Customization.objects.filter(name__in=customizations))
    notification.save()
    return notification.id


@swagger_auto_schema(method="POST",  auto_schema=None,
                     operation_description=f"Sends a message that is about ipvd or integrations."
                                           f"The possible subjects are {','.join(MESSAGE_TYPES.keys())}",
                     request_body=openapi.Schema(
                         type=openapi.TYPE_OBJECT,
                         properties={
                             "asset": asset__body,
                             "message": message__body,
                             "type": type__body,
                             "userEmail": user_email__body,
                             "userName": user_name__body
                         },
                         required=["message", "type", "userEmail", "userName"]
                     ))
@api_view(['POST'])
@permission_classes((AllowAny, ))
def send_event(request):
    feedback_enabled = cloud_portal_customization_cache(
        request.CUSTOMIZATION, 'config').get('feedback_enabled', False)
    if not feedback_enabled:
        raise APIServiceException(
            'Feedback is currently unavailable', ErrorCodes.service_unavailable)

    try:
        validation_error = False
        error_data = {}

        if 'type' not in request.data or not request.data['type']:
            validation_error = True
            error_data['type'] = ['This field is required.']

        if 'type' in request.data\
            and request.data['type'] not in [MESSAGE_TYPES.ipvd_feedback_page,
                                             MESSAGE_TYPES.ipvd_feedback_device]\
                and 'asset' not in request.data:
            validation_error = True
            error_data['asset'] = ['This field is required.']

        if 'message' not in request.data:
            validation_error = True
            error_data['message'] = ['This field is required.']

        if 'userEmail' not in request.data:
            validation_error = True
            error_data['userEmail'] = ['This field is required.']

        if 'userName' not in request.data:
            validation_error = True
            error_data['userName'] = ['This field is required.']

        if validation_error:
            raise APIRequestException('Not enough parameters in request', ErrorCodes.wrong_parameters,
                                      error_data=error_data)

        asset_id = ''
        if request.data['type'] not in [MESSAGE_TYPES.ipvd_feedback_page,
                                        MESSAGE_TYPES.ipvd_feedback_device]:
            asset = Asset.objects.filter(id=request.data['asset']).first()
            if asset:
                request.data['asset'] = asset.name
                asset_id = asset.id
        else:
            request.data['type'] = MESSAGE_TYPES.ipvd_feedback

        request.data['sender_email'] = request.data['userEmail']
        request.data['sender_name'] = request.data['userName']

        ip = get_client_ip(request)
        logging.info(
            f"ip: {ip}\t user: {request.user}\nrequest data: {request.data}")

        notifications_api.send_feedback(
            request.data['type'], asset_id, request.data, request=request)

    except ValidationError as error:
        error_data = error.detail if hasattr(error, 'detail') else None
        raise APIRequestException(
            error.message, ErrorCodes.wrong_parameters, error_data=error_data)
    return api_success()


@swagger_auto_schema(method="POST",  auto_schema=None,
                     operation_description="Sends an email to the target user. Mainly used by clouddb.",
                     manual_parameters=[external_id__query_param],
                     request_body=openapi.Schema(
                         type=openapi.TYPE_OBJECT,
                         properties={
                             "customization": customization__body,
                             "message": message__body,
                             "type": notification_type__body,
                             "user_email": notification_user_email__body,
                             "userFullName": notification_user_name__body
                         },
                         required=["customization",
                                   "message", "type", "user_email"]
                     ))
@api_view(['POST'])
@permission_classes((AllowAny, ))
def send_notification(request):
    try:
        validation_error = False
        error_data = {}

        external_id = request.data.get('id')
        if external_id:  # external service generated an id for this message to track it
            msg = notifications_api.find_message(external_id)
            if msg:
                # there is already a message with this id - do not send the message, respond with status
                serializer = MessageStatusSerializer(msg, many=False)
                return api_success(serializer.data)

        if 'user_email' not in request.data or not request.data['user_email']:
            validation_error = True
            error_data['user_email'] = ['This field is required.']

        if 'type' not in request.data or not request.data['type']:
            validation_error = True
            error_data['type'] = ['This field is required.']
        if 'message' not in request.data:
            validation_error = True
            error_data['message'] = ['This field is required.']

        if 'customization' not in request.data or not request.data['customization']:
            validation_error = True
            error_data['customization'] = ['This field is required.']

        if validation_error:
            raise APIRequestException('Not enough parameters in request', ErrorCodes.wrong_parameters,
                                      error_data=error_data)
        if not NotificationRateThrottle().allow_request(request=request, view=None):
            logger.warning(
                f'Request throttled for {request.data["user_email"]}::{request.data["type"]}'
                f' in customization {request.data["customization"]}'
            )
            raise APITooManyRequestsException('Too many request. Please try again later')
        # Clouddb doesn't always return a full name so try to get it from cloud portal
        if 'userFullName' not in request.data['message'] or not request.data['message']['userFullName']:
            user_account = Account.objects.filter(
                email=request.data['user_email']).first()
            if user_account:
                request.data['message']['userFullName'] = user_account.get_full_name()

        notifications_api.send(request.data['user_email'],
                               request.data['type'],
                               request.data['message'],
                               customization=request.data['customization'],
                               external_id=external_id)
    except ValidationError as error:
        error_data = error.detail if hasattr(error, 'detail') else None
        raise APIRequestException(
            error.message, ErrorCodes.wrong_parameters, error_data=error_data) from error
    return api_success()


