// @ts-check
import fs from 'fs';
import path from 'path';
import process from 'process';
import { fileURLToPath } from 'url';

import { sum } from 'lodash-es';

import { binnedLint } from './binned-lint.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const front_end = path.dirname(__dirname);
process.chdir(front_end);

const blacklistFile = 'type-lint-blacklist.js';
const originalEsprintrc = fs.readFileSync('.esprintrc', { encoding: 'utf-8' });
/** @type {string[]} */
const esprintPaths = JSON.parse(originalEsprintrc).paths;
const tsPaths = esprintPaths.filter(f => f.endsWith('ts'));

binnedLint(blacklistFile, { globPatterns: tsPaths }).then(issues => {
    const errorCount = Object.fromEntries(
        Object.entries(issues).map(([filePath, fileIssues]) => [filePath, fileIssues.length]),
    );
    const lines = [
        '/* eslint-disable prettier/prettier */',
        '/** Files with type linting errors.',
        ` * File generated by \`update-${blacklistFile.replace('.js', '')}\`. */`,
        `const errorCount = ${JSON.stringify(errorCount, null, 4)};`,
        `/* ✖ ${sum(Object.values(errorCount))} problems */\n`,
        'module.exports = Object.keys(errorCount);\n',
    ];
    fs.writeFileSync(`./linting/${blacklistFile}`, lines.join('\n'));
});
