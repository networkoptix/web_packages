// @ts-check
import fs from 'fs';
import path from 'path';
import process from 'process';
import { fileURLToPath } from 'url';

import { sum } from 'lodash-es';

import { binnedLint } from './binned-lint.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const front_end = path.dirname(__dirname);
process.chdir(front_end);

const blacklistFile = 'global-style-blacklist.js';

binnedLint(blacklistFile, { binSize: 40000 }).then(issues => {
    const errorCount = Object.fromEntries(
        Object.entries(issues).map(([filePath, fileIssues]) => {
            if (filePath.endsWith('.ts')) {
                filePath = `${filePath}/*inline-template-*.component.html`;
            }
            return [filePath, fileIssues.length];
        }),
    );
    const lines = [
        '/* eslint-disable prettier/prettier */',
        '/** Templates using using global styles.',
        ` * Includes elements selected by global styles and use of global style classes`,
        ` * File generated by \`update-${blacklistFile.replace('.js', '')}\`. */`,
        `const errorCount = ${JSON.stringify(errorCount, null, 4)};`,
        `/* ✖ ${sum(Object.values(errorCount))} problems */\n`,
        'module.exports = Object.keys(errorCount);\n',
    ];
    fs.writeFileSync(`./linting/${blacklistFile}`, lines.join('\n'));
});
